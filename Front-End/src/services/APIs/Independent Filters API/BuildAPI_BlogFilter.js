export function BuildAPI_BlogFilter({ALLfilters}) {

    //Create Filter IN Object
    const customBlogFilter = {};

{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}





    //Step 1 ==>  ALL tags
    if (ALLfilters.tag) {
        customBlogFilter.details = {
            
            postBody: {

                tags: {
                    name: {
                        // $eqi: "Travel",
        
                        $eqi: ALLfilters.tag,
                    }
                }

            }
        };

    }



{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

    return customBlogFilter;
}