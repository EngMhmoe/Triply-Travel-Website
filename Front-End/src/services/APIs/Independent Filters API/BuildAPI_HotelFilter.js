export function BuildAPI_HotelFilter({ALLfilters}) {

    //Create Filter IN Object
    const customHotelFilter = {};

{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}





    //Step 1 ==>  ALL stars
    if (ALLfilters.stars.length) {

        customHotelFilter.details = {

            hotelInfo: {

                hotelStars: {
                    // $eq: 5,

                    // $in: [5 , 4],
                    
                    $in: ALLfilters.stars,
                },

            },

        };

    }


    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////


    //Step 2 ==>  ALL facilities
        if(ALLfilters.facilities.length)
        {

            customHotelFilter.facilities = {

                name: {

                    // $eq: "wifi",
    
                    // $in: ["air_condition"],
    
                    // $eqi: ["air_condition"],

                    $eqi: ALLfilters.facilities,
    
                }

            }
            
        }





{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

    return customHotelFilter;
}