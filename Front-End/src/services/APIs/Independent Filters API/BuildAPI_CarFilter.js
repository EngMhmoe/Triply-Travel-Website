export function BuildAPI_CarFilter({ALLfilters}) {

    //Create Filter IN Object
    const customCarFilter = {};

{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}





    //Step 1 ==>  ALL brands
    if (ALLfilters.brands.length) {

        customCarFilter.brand = {
            // $in: ["audi" , "bmw"],

            $eqi: ALLfilters.brands,
        };

    }


    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////


    //Step 2 ==>  ALL conditions
    if (ALLfilters.conditions.length) {

        customCarFilter.condition = {
            $in: ["new" , "used"],

            $eqi: ALLfilters.conditions,
        };

    }


    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////

    
    //Step 3 ==>  ALL listedBy
    if (ALLfilters.listedBy.length) {

        customCarFilter.listedBy = {
            // $eqi: ["dealer"],

            $eqi: ALLfilters.listedBy,
        };

    }
    
    
    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////
    

    //Step 4 ==>  ALL fuels
    if (ALLfilters.fuels.length) {

        customCarFilter.fuel = {
            // $eqi: ["diesel" , "electric"],

            $eqi: ALLfilters.fuels,
        };

    }
    
    
    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////
    
    
    //Step 5 ==>  ALL transmissions
    if (ALLfilters.transmissions.length) {

        customCarFilter.transmission = {
            // $eqi: ["automatic"],

            $eqi: ALLfilters.transmissions,
        };

    }





{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

    return customCarFilter;
}