export function BuildAPI_FoodFilter({ALLfilters}) {

    //Create Filter IN Object
    const customFoodFilter = {};

{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}





    //Step 1 ==>  ALL cuisines
    if (ALLfilters.cuisineType.length) {

        customFoodFilter.cuisine = {
            // $eq: "Arabic",

            $eqi: ALLfilters.cuisineType,
        };

    }


    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////


    //Step 2 ==>  ALL Ratings
    if (ALLfilters.ratings.length) {

        customFoodFilter.rating = {
            // $gte: [3],

            $gte: ALLfilters.ratings,
        }; 

    }


    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////


    //Step 3 ==>  ALL ServingSize
    if (ALLfilters.servingSize.length) {

        customFoodFilter.details = {
            menuInfo: {
                servingSize: {
                    // $in: [3],

                    $in: ALLfilters.servingSize,
                },
            },
        };

    }


    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////


    //Step 4 ==>  ALL spicyLevel
    if (ALLfilters.spicyLevel.length) {

        customFoodFilter.details = {
            menuInfo: {
                spicyLevel: {
                    // $eqi: ["Low"],

                    $eqi: ALLfilters.spicyLevel,
                },
            },
        };

    }





{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

    return customFoodFilter;
}