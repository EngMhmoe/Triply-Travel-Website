export function BuildAPI_TourFilter({ALLfilters}) {

    //Create Filter IN Object
    const customTourFilter = {};

{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}





    //Step 1 ==>  ALL durations
    if(ALLfilters.durations.length)
    {
        customTourFilter.duration = {
            // $in: [4,5],
            $in: ALLfilters.durations,
        }
    }


    ///////////////////////////////////////////////////////////////////////
    ///////////////////////////////////////////////////////////////////////


    //Step 2 ==>  ALL attractions
    if (ALLfilters.attractions.length) {
        customTourFilter.attractions = {
            name:{
                // $in: ["5th Avenue"],
                
                // $in: ALLfilters.attractions,

                $eqi: ALLfilters.attractions,
            }
        };
    }





{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
{/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

    return customTourFilter;
}