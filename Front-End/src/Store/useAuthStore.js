import { create } from "zustand";

/*====================================================================================================
End Imports
====================================================================================================*/

/*====================================================================================================
Start Auth Store
====================================================================================================*/

export const useAuthStore = create((set) => ({
    /*==================================================================================================
  Initial State
  ==================================================================================================*/

  token: localStorage.getItem("token") || null,

   /*==================================================================================================
  Actions
  ==================================================================================================*/

  login: (token) => {
    localStorage.setItem("token", token);
    set({ token }); // 🔥 أهم سطر
  },

  logout: () => {
    localStorage.removeItem("token");
    set({ token: null });
  },
}));