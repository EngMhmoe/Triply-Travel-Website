//============================================================
// React
//============================================================
import { useState } from "react";

//============================================================
// Data
//============================================================
import { categories } from "../../../Data/Home/ALLCategoriesTours";

//============================================================
// Translation
//============================================================
import { useTranslation } from "react-i18next";

/*====================================================================================================
Step 2 ==> Component
======================================================================================================*/

export default function FilterTabs({ setFilters }) {
  /*==================================================================================================
  State
  ==================================================================================================*/

  const [active, setActive] = useState("All Category");

  /*==================================================================================================
  Hooks
  ==================================================================================================*/
  const { t } = useTranslation();

  /*==================================================================================================
  Classes
  ==================================================================================================*/
  const classes = {
    Wrapper:
      "flex flex-wrap justify-center items-center gap-3 bg-(--primary-pera) sm:p-1.5 p-5 rounded-full rounded-br-none font-bold text-black duration-1000",

    Button:
      "px-5 py-2 rounded-full rounded-br-none capitalize transition duration-1000 cursor-pointer",

    Active: "bg-(--primary-color) text-white",

    InActive: "bg-white shadow-sm hover:bg-(--primary-color2) hover:text-white",
  };

  /*==================================================================================================
  Handlers
  ==================================================================================================*/
  function FilterCategory(selectedCategory) {
    setActive(selectedCategory);

    setFilters((prev) => ({
      ...prev,

      categories:
        selectedCategory === "All Category"
          ? ["Historical", "City", "Beach"]
          : [selectedCategory],
    }));
  }

  /*==================================================================================================
  Render
  ==================================================================================================*/

  return (
    <section className={classes.Wrapper}>
      {categories.map((category) => (
        <button
          key={category}
          onClick={() => FilterCategory(category)}
          className={`${classes.Button} ${
            active === category ? classes.Active : classes.InActive
          }`}
        >
          {t(category.toLowerCase())}
        </button>
      ))}
    </section>
  );
}

/*====================================================================================================
End Component
======================================================================================================*/
