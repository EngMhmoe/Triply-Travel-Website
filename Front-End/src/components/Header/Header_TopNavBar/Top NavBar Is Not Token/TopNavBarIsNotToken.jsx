/*====================================================================================================
Start Imports
====================================================================================================*/
//============================================================
// React Router
//============================================================
import { Link } from "react-router-dom";

//============================================================
// Translation
//============================================================
import { useTranslation } from "react-i18next";

//============================================================
// Store
//============================================================
import { useDarkModeStore } from "../../../../Store/useDarkModeStore";

//============================================================
// Data
//============================================================
import { AUTH_LINKS } from "../../../../Data/Header/authLinks";

//============================================================
// React Icons
//============================================================
import { BiLogIn } from "react-icons/bi";
import { FaUserInjured } from "react-icons/fa";

//============================================================
// UI / Animations
//============================================================
import { motion } from "framer-motion";
/*====================================================================================================
End Imports
====================================================================================================*/

export default function TopNavBarIsNotToken() {
  //==========================================================
  // Translation
  //==========================================================
  const { t } = useTranslation();

  //==========================================================
  // Dark Mode
  //==========================================================
  const { DarkMode: darkMode } = useDarkModeStore();

  //==========================================================
  // Styles
  //==========================================================
  const classes = {
    wrapper: `flex items-center justify-between gap-3 capitalize ${
      darkMode ? "text-white/90" : ""
    }`,

    link: "flex items-center gap-2 cursor-pointer transition-colors duration-1000 hover:text-orange-400",

    icon: `text-xl`,
  };

  return (
    <motion.section
      initial={{ scale: 0 }}
      animate={{ scale: 1 }}
      transition={{ duration: 4 }}
      className={classes.wrapper}
    >
      {AUTH_LINKS.map((link) => {
        return (
          <Link key={link.id} to={link.href} className={classes.link}>
            <div className={classes.icon}>
              {link.name === "login" && <BiLogIn />}

              {/* /////////////////////////////////// */}
              {/* /////////////////////////////////// */}

              {link.name === "sign up" && <FaUserInjured />}
            </div>

            {/* //////////////////////////////////////////////////////////////////////// */}
            {/* //////////////////////////////////////////////////////////////////////// */}

            {t(link.name)}
          </Link>
        );
      })}
    </motion.section>
  );
}
