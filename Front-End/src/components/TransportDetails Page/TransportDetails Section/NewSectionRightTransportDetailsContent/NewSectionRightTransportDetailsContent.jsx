//import Components UI
import DataBox from "../../../../UI/Details_Page/Section RIGHT/booking/DataBox2";

//import Components NEW
import CarTotalBox from "./CarTotalBox";

//import react icons
import { ImLocation2 } from "react-icons/im";
import { BsCalendar2DateFill } from "react-icons/bs";
import { MdOutlineAccessTimeFilled } from "react-icons/md";

//import useBookingCarStore
import useBookingCarStore from "../../../../Store/useBookingCarStore";
import { useEffect } from "react";

export default function NewSectionRightTransportDetailsContent({
  TransportDataDetails,
}) {
  //styling
  const styling = { icon: "text-2xl text-(--primary-color2)" };

  ///////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////

  //useBookingCarStore
  const { booking, updateBooking } = useBookingCarStore();

  useEffect(() => {
    updateBooking({
      PickingUp:
        TransportDataDetails?.location?.city +
        "," +
        TransportDataDetails?.location?.address,
    });
  }, [booking.PickingUp]);

  return (
    <section className="space-y-5">
      {/* Picking Up Location */}
      <DataBox
        Data={{
          title: "Picking Up Location",
          icon: <ImLocation2 className={styling.icon} />,
          type: "text",
          DefaultType: "Picking Up Location",
        }}
        booking={booking}
        updateBooking={updateBooking}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Pick Up date */}
      <DataBox
        Data={{
          title: "Pick Up Date",
          icon: <BsCalendar2DateFill className={styling.icon} />,
          type: "date",
          DefaultType: "Pick Up Date",
        }}
        booking={booking}
        updateBooking={updateBooking}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Pick Up Time */}
      <DataBox
        Data={{
          title: "Pick Up Time",
          icon: <MdOutlineAccessTimeFilled className={styling.icon} />,
          type: "time",
          DefaultType: "Pick Up Time",
        }}
        booking={booking}
        updateBooking={updateBooking}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Drop Off Location */}
      <DataBox
        Data={{
          title: "Drop Off Location",
          icon: <ImLocation2 className={styling.icon} />,
          type: "text",
          DefaultType: "Drop Off Location",
        }}
        booking={booking}
        updateBooking={updateBooking}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Drop Off date */}
      <DataBox
        Data={{
          title: "Drop Off date",
          icon: <BsCalendar2DateFill className={styling.icon} />,
          type: "date",
          DefaultType: "Drop Off Date",
        }}
        booking={booking}
        updateBooking={updateBooking}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Drop Off Time */}
      <DataBox
        Data={{
          title: "Drop Off Time",
          icon: <MdOutlineAccessTimeFilled className={styling.icon} />,
          type: "time",
          DefaultType: "Drop Off Time",
        }}
        booking={booking}
        updateBooking={updateBooking}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Total ==> ok */}
      <CarTotalBox TransportDataDetails={TransportDataDetails} />
    </section>
  );
}
