import NewSectionLeftTransportDetailsContent from "./TransportDetails Section/NewSectionLeftTransportDetailsContent/NewSectionLeftTransportDetailsContent";
import NewSectionRightTransportDetailsContent from "./TransportDetails Section/NewSectionRightTransportDetailsContent/NewSectionRightTransportDetailsContent";
