//import React
import React, { useState, useMemo } from "react";

//import framer-motion
import { motion, AnimatePresence } from "framer-motion";

//import React ICons
import {
  FiSearch,
  FiEye,
  FiEdit2,
  FiTrash2,
  FiX,
  FiMapPin,
  FiLoader,
  FiAlertTriangle,
  FiCheckCircle,
  FiChevronLeft,
} from "react-icons/fi";

import { FaHotel, FaPlane, FaCar, FaShip } from "react-icons/fa";

// import Component UI
import TopBar from "../../../../UI/My personal files/Container NEW IS Header With ALL Page/TopBar";
import TableBookings from "../../../../UI/My personal files/TableBookings";
import EmptyState from "../../../../UI/My personal files/Container Table/EmptyState";

// import Component NEW
import SearchBar from "./NEW My Listing/SearchBar";
import ListingRow from "./ListingRow";
import LoadMoreButton from "./LoadMoreButton";
import ViewModal from "./ViewModal";
import { EditModal } from "./EditModal";
import DeleteModal from "./DeleteModal";

/* ------------------------------------------------------------------ */
/* Sample Data                                                         */
/* ------------------------------------------------------------------ */
import { INITIAL_LISTINGS } from "../INITIAL_LISTINGS";

import { useUserDataStore } from "../../../../Store/useUserDataStore";

const PAGE_SIZE = 4;

/* ------------------------------------------------------------------ */
/* Main App                                                             */
/* ------------------------------------------------------------------ */
export default function MyListingSection() {
  //(1) Data User == FullUserName && Email
  const { userData } = useUserDataStore();

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //listings
  const [listings, setListings] = useState(INITIAL_LISTINGS);

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //search
  const [search, setSearch] = useState("");

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //visibleCount
  const [visibleCount, setVisibleCount] = useState(PAGE_SIZE);

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //loadingMore
  const [loadingMore, setLoadingMore] = useState(false);

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //modal
  const [modal, setModal] = useState({ type: null, listing: null });

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //filtered Search Title
  const filtered = useMemo(() => {
    const q = search.trim().toLowerCase();
    if (!q) return listings;
    return listings.filter((l) => l.title.toLowerCase().includes(q));
  }, [listings, search]);

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //visible
  const visible = filtered.slice(0, visibleCount);

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //remaining
  const remaining = filtered.length - visible.length;

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //Function handleLoadMore
  const handleLoadMore = () => {
    setLoadingMore(true);
    setTimeout(() => {
      setVisibleCount((v) => v + PAGE_SIZE);
      setLoadingMore(false);
    }, 1000);
  };

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //Function closeModal
  const closeModal = () => setModal({ type: null, listing: null });

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //Function handleDeleteConfirm
  const handleDeleteConfirm = () => {
    setListings((prev) => prev.filter((l) => l.id !== modal.listing.id));
    closeModal();
  };

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  //Function handleSaveEdit
  const handleSaveEdit = (updated) => {
    setListings((prev) => prev.map((l) => (l.id === updated.id ? updated : l)));
    closeModal();
  };

  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////

  return (
    <div
      style={{
        flex: 1,
        padding: "28px 20px",
        overflowX: "hidden",
      }}
      className="bg-[#ecf5fc] rounded-[40px] border border-orange-200"
    >
      {/* ── Top Bar ────────────────────────────────────────────── */}
      <section style={{ marginBottom: 28 }}>
        <TopBar mainText={"My Listing"} userData={userData} />
      </section>

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}

      <div className="mx-auto max-w-5xl rounded-2xl bg-white p-4 shadow-sm sm:p-6">
        {/* Header */}
        <div className="border-b border-slate-100 pb-5">
          <SearchBar
            value={search}
            onChange={(v) => {
              setSearch(v);
              setVisibleCount(PAGE_SIZE);
            }}
          />
        </div>

        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}

        {/* Table header (desktop only) */}
        <div className="mt-4 hidden grid-cols-[minmax(0,2.2fr)_0.8fr_0.7fr_0.9fr_0.8fr_auto] gap-4 px-2 pb-2 text-xs font-semibold uppercase tracking-wide text-slate-400 sm:grid">
          <span>Listing Info</span>
          <span>Type</span>
          <span>Views</span>
          <span>Publish On</span>
          <span>Status</span>
          <span className="text-right">Action</span>
        </div>

        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}

        {/* Rows */}
        <div>
          <AnimatePresence mode="popLayout">
            {visible.length > 0 ? (
              visible.map((listing) => (
                <ListingRow
                  key={listing.id}
                  listing={listing}
                  onView={() => setModal({ type: "view", listing })}
                  onEdit={() => setModal({ type: "edit", listing })}
                  onDelete={() => setModal({ type: "delete", listing })}
                />
              ))
            ) : (
              <EmptyState />
            )}
          </AnimatePresence>
        </div>

        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
        {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}

        <LoadMoreButton
          loading={loadingMore}
          onClick={handleLoadMore}
          remaining={remaining}
        />
      </div>

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Modals */}
      <AnimatePresence>
        {modal.type === "view" && (
          <ViewModal listing={modal.listing} onClose={closeModal} />
        )}
        {modal.type === "edit" && (
          <EditModal
            listing={modal.listing}
            onClose={closeModal}
            onSave={handleSaveEdit}
          />
        )}
        {modal.type === "delete" && (
          <DeleteModal
            listing={modal.listing}
            onClose={closeModal}
            onConfirm={handleDeleteConfirm}
          />
        )}
      </AnimatePresence>

      <section className="my-10"></section>

      {/* //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* //////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* ── Recent Bookings Table ──────────────────────────────── */}
      <TableBookings condition={"My Listing"} />
    </div>
  );
}
