//import React
import { useEffect } from "react";

/*===========================================================
Start import Components (1)
=============================================================*/
//Step 1 ==> import Components UI
import HerSection from "../../UI/Hero Section ALL Page/HerSection";
import Details_Page_Section from "../../UI/Details_Page/Details_Page_Section";

//Step 2 ==> import Components NEW
import NewSectionLeftTourDetailsContent from "./TourDetails Section/NewSectionLeftTourDetailsContent/NewSectionLeftTourDetailsContent";
import NewSectionRightTourDetailsContent from "./TourDetails Section/NewSectionRightTourDetailsContent/NewSectionRightTourDetailsContent";
/*===========================================================
End import Components (1)
=============================================================*/

//////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////

/*===========================================================
Start import React Icons (2)
=============================================================*/
import { MdDateRange } from "react-icons/md";
import { HiUserGroup } from "react-icons/hi2";
import { FaClock, FaGlobeAmericas } from "react-icons/fa";
/*===========================================================
End import React Icons (2)
=============================================================*/

//////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////

/*===========================================================
Start import Hooks (4)
=============================================================*/
import { useDetailsPage } from "../../Hooks/useDetailsPage";
import useBookingTourStore from "../../Store/useBookingTourStore";
/*===========================================================
End import Hooks (4)
=============================================================*/

//import useTranslation
import { useTranslation } from "react-i18next";

//import useDarkModeStore
import { useDarkModeStore } from "../../Store/useDarkModeStore";

// ===>>>
export default function TourDetailsPage() {
  //DarkMode
  const { DarkMode } = useDarkModeStore();

  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////

  //Step 1 ==> Booking Tour Store
  const { booking: bookingTour, updateBooking } = useBookingTourStore();

  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////

  //step 2 ==> useDetailsPage
  const {
    DetailsPage_Styling,
    getDataItemDetails,
    isValid,
    handleBooking: handleBookingTour,
  } = useDetailsPage({
    booking: bookingTour,
    requiredFields: bookingTour.typeCondition,
    DarkMode,
  });

  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////

  //step 3 ==> HotelDetailsInfo
  const TourDetailsInfo = [
    {
      name: "Tour Type",
      Data: getDataItemDetails?.tourType,
      icon: <FaGlobeAmericas />,
    },
    {
      name: "Duration",
      Data: `${getDataItemDetails?.duration} Days`,
      icon: <FaClock />,
    },

    //Data
    {
      name: "Data",
      Data: getDataItemDetails?.date,
      icon: <MdDateRange />,
    },

    //Group Size
    {
      name: "Group Size",
      Data: getDataItemDetails?.groupSize,
      icon: <HiUserGroup />,
    },
  ];

  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////

  useEffect(() => {
    updateBooking({
      type: getDataItemDetails?.tourType,
    });
  }, [getDataItemDetails]);

  ////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////

  //t, i18n
  const { t, i18n } = useTranslation();

  ////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////

  useEffect(() => {
    window.scrollTo({
      top: 0,
      behavior: "smooth",
    });
  }, []);

  /////////////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////////////

  return (
    <section className={DetailsPage_Styling.Styling1}>
      {/* Component HerSection UI ==> (1)  */}
      <HerSection
        NamePage={"Tour Single"}
        src={"bg-[url('/Images/Tour_Img_HerSection.jpg')]"}
        position={"center"}
        t={t}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Component TourDetailsSection ==> (2)*/}
      <section className={DetailsPage_Styling.Styling2}>
        <Details_Page_Section
          //Step 1 ==> NEW Section Left Content ALL Details
          ContainerDataDetails={getDataItemDetails}
          ///////////////////////////////////////////////////////////
          ///////////////////////////////////////////////////////////

          DataDetailsInfo={TourDetailsInfo}
          ///////////////////////////////////////////////////////////
          ///////////////////////////////////////////////////////////

          NewSectionLeftContent={
            <NewSectionLeftTourDetailsContent
              TourDataDetails={getDataItemDetails}
            />
          }
          //////////////////////////////////////////////////////////////////////////////////////////////
          //////////////////////////////////////////////////////////////////////////////////////////////
          //////////////////////////////////////////////////////////////////////////////////////////////

          //Step 2 ==> NEW Section Right Content ALL Details
          NewSectionRightContent={
            <NewSectionRightTourDetailsContent
              TourDataDetails={getDataItemDetails}
            />
          }
          ///////////////////////////////////////////////////////////
          ///////////////////////////////////////////////////////////

          handleBooking={handleBookingTour}
          ///////////////////////////////////////////////////////////
          ///////////////////////////////////////////////////////////

          isValid={isValid}
        />
      </section>
    </section>
  );
}
