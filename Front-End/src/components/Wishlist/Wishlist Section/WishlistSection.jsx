//import Components
import ContentWishlist from "./ContentWishlist";
import HeaderWishlist from "./HeaderWishlist";
import SkeletonLoading from "./SkeletonLoading";
import ModakAddToCartAndDelete from "../../../UI/ModelAddToCart&Delete";
import FooterWishlist from "./FooterWishlist";

//import React Hooks
import { useState, useEffect, useRef } from "react";

//import React Icons
import { FaShoppingCart } from "react-icons/fa";

//import react-hot-toast
import { Toaster } from "react-hot-toast";

//import useStor
import { useWishlistStore } from "../../../Store/useWishlistStore";

//import Hooks
import { useItemActions } from "../../../Hooks/useItemActions";
import { useShopActions } from "../../../Hooks/useShopActions";
import { useToast } from "../../../Hooks/useToast";

export default function WishlistSection() {
  //getWishlist AND setWishlist
  const { getWishlist, setWishlist } = useWishlistStore();

  //modal add || delete == NO
  const [modal, setModal] = useState(null); // add | delete

  //Select Item Id == NO
  const [selectItemId, setSelectItemId] = useState(null);

  // Hook is useItemActions
  const { ShowModelDelete, confirmDelete, DeleteItem } = useItemActions({
    //
    get: getWishlist,
    set: setWishlist,

    //
    setModal: setModal,

    //
    selectItemId: selectItemId,
    setSelectItemId: setSelectItemId,

    //
    textToast: "Removed To Wishlist",
    conditionConfirmDelete: "Item",
  });

  // Hook is useShopActions
  const { AddToCart } = useShopActions(getWishlist);

  // Hook is useToast
  const { toastError } = useToast();

  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////

  //Check List Card OR Grid Card
  const [view, setView] = useState("list");

  //loading
  const [loading, setLoading] = useState(true);

  //cartRef
  const cartRef = useRef();

  //function getFinalPrice
  const getFinalPrice = (price, discount) => {
    return price - (price * discount) / 100;
  };

  // function ShowModelAddToCart
  function ShowModelAddToCart(selectItemId) {
    //Show Model delete
    setModal("add");

    //set Select Item Id
    setSelectItemId(selectItemId);
  }

  // function confirmAddToCart
  function confirmAddToCart() {
    //(2) ==> currentCart in LocalStorage
    const currentCart = JSON.parse(localStorage.getItem("Carts")) || [];

    //(5) ==> Filter Carts In LocalStorage
    const FilterCartsInLocalStorage = currentCart.find(
      (item) => item.documentId == selectItemId,
    );

    if (!FilterCartsInLocalStorage) {
      // Cal Function AddToCart is Hook
      AddToCart(selectItemId);

      // Cal Function AddToCart is Hook
      DeleteItem();
    } else {
      toastError("Already in the cart");
    }
  }

  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////

  // ⏳ Skeleton Loading
  useEffect(() => {
    setTimeout(() => {
      setLoading(false);
    }, 1200);
  }, []);

  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////////////////////////

  return (
    <div className="max-w-7xl m-auto xl:mx-auto sm:mx-6 mb-15 relative">
      <Toaster />
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* New */}
      {/* 🛒 Cart Icon */}
      <div
        ref={cartRef}
        className="fixed visited:hidden top-6 right-6 bg
        text-transparent
         p-3 rounded-full"
      >
        <FaShoppingCart />
      </div>
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* Header */}
      <HeaderWishlist view={view} setView={setView} />
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* Skeleton Loading */}
      <SkeletonLoading loading={loading} />
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ContentWishlist */}
      <ContentWishlist
        ShowModelDelete={ShowModelDelete}
        ShowModelAddToCart={ShowModelAddToCart}
        /////////////////////////////////////
        loading={loading}
        view={view}
        getFinalPrice={getFinalPrice}
        setModal={setModal}
      />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* Footer Wishlist */}
      <FooterWishlist />

      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}

      {/* 🧊 MODAL */}
      <ModakAddToCartAndDelete
        modal={modal}
        confirmDelete={confirmDelete}
        confirmAddToCart={confirmAddToCart}
        //
        setModal={setModal}
        //
        ContentConfirmAddToCart={"Are you sure you want to adding this Cart ?"}
        ContentConfirmDelete={"Are you sure you want to delete this Wishlist ?"}
      />
    </div>
  );
}
