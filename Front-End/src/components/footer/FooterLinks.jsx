/*====================================================================================================
Step 1 ==> Imports
======================================================================================================*/

//============================================================
// React Router
//============================================================
import { Link } from "react-router-dom";

//============================================================
// Icons
//============================================================
import { GoChevronRight } from "react-icons/go";

//============================================================
// Hooks
//============================================================
import { useTranslation } from "react-i18next";

//============================================================
// FadeUpMotion
//============================================================
import FadeUpMotion from "../../UI/FreeMotions/FadeUpMotion";

/*====================================================================================================
Step 2 ==> Component
======================================================================================================*/

export default function FooterLinks({ title, links }) {
  /*==================================================================================================
  Hooks
  ==================================================================================================*/

  const { t } = useTranslation();

  /*==================================================================================================
  Classes
  ==================================================================================================*/
  const FOOTER_LINKS_CLASSES = {
    title: "relative xl:ml-7 mb-10 text-lg font-bold text-white",

    titleLine: "absolute left-0 -bottom-4 h-0.5 w-9 bg-(--primary-color)",

    titleSmallLine: "absolute left-11 -bottom-4 h-0.5 w-3 bg-(--primary-color)",

    list: "space-y-3 xl:ml-7",

    item: "group relative flex w-fit cursor-pointer items-center gap-1 font-semibold text-gray-200 duration-500 hover:ml-3 hover:text-orange-400",

    icon: "text-(--primary-color2)",

    underline:
      "absolute left-0 -bottom-1 h-0.5 w-0 bg-(--primary-color2) transition-all duration-700 group-hover:w-full",
  };

  /*==================================================================================================
  Render
  ==================================================================================================*/

  return (
    <section>
      {/*==============================================================================================
      Title
      ==============================================================================================*/}
      <FadeUpMotion>
        <h3 className={FOOTER_LINKS_CLASSES.title}>
          {t(title)}

          {/* ///////////////////////////////////////////////////// */}
          {/* ///////////////////////////////////////////////////// */}

          <FadeUpMotion>
            <span className={FOOTER_LINKS_CLASSES.titleLine}></span>

            {/* ///////////////////////////////////////////////////// */}
            {/* ///////////////////////////////////////////////////// */}

            <span className={FOOTER_LINKS_CLASSES.titleSmallLine}></span>
          </FadeUpMotion>
        </h3>
      </FadeUpMotion>

      {/* /////////////////////////////////////////////////////////////////////////////////////// */}
      {/* /////////////////////////////////////////////////////////////////////////////////////// */}

      {/*==============================================================================================
      Links
      ==============================================================================================*/}
      <ul className={FOOTER_LINKS_CLASSES.list}>
        {links.map((link) => (
          <FadeUpMotion>
            <li key={link.id} className={FOOTER_LINKS_CLASSES.item}>
              <GoChevronRight className={FOOTER_LINKS_CLASSES.icon} />

              {/* ///////////////////////////////////////////////////// */}
              {/* ///////////////////////////////////////////////////// */}

              <Link to={link.href}>{t(link.name)}</Link>

              {/* ///////////////////////////////////////////////////// */}
              {/* ///////////////////////////////////////////////////// */}

              <span className={FOOTER_LINKS_CLASSES.underline}></span>
            </li>
          </FadeUpMotion>
        ))}
      </ul>
    </section>
  );
}

/*====================================================================================================
End Component
======================================================================================================*/
