import { useTranslation } from "react-i18next";

/*====================================================================================================
Step 2 ==> Component
======================================================================================================*/

export default function MainTitle({
  mainTitle1,
  mainTitle2,
  mainTitle3,
  condition,
}) {
  /*==================================================================================================
  Hooks
  ==================================================================================================*/

  const { t } = useTranslation();

  /*==================================================================================================
  Classes
  ==================================================================================================*/

  const classes = {
    Title: `MainTitle  mt-2 font-bold lg:text-3xl sm:text-3xl text-2xl text-shadow-lg text-shadow-black/15 capitalize ${condition === "Testimonial" && "text-white"}`,

    Highlight: `text-(--primary-color) text-shadow-md text-shadow-white/20 ${condition === "Testimonial" && "text-shadow-none"}`,
  };

  /*==================================================================================================
  Render
  ==================================================================================================*/

  return (
    <section>
      <h2 className={classes.Title}>
        {t(mainTitle1.toLowerCase())}

        <span className={classes.Highlight}>
          {" "}
          {t(mainTitle2.toLowerCase())}{" "}
        </span>

        {t(mainTitle3.toLowerCase())}
      </h2>
    </section>
  );
}

/*====================================================================================================
End Component
======================================================================================================*/
