/*====================================================================================================
Step 1 ==> Imports
======================================================================================================*/

//============================================================
// Translation
//============================================================
import { useTranslation } from "react-i18next";
import { useDarkModeStore } from "../Store/useDarkModeStore";

//============================================================
// Animations
//============================================================
import FadeUpMotion from "./FreeMotions/FadeUpMotion";

/*====================================================================================================
Step 2 ==> Component
======================================================================================================*/

export default function Description({ Des }) {
  /*==================================================================================================
  Hooks
  ==================================================================================================*/

  const { t } = useTranslation();

  const { DarkMode: darkMode } = useDarkModeStore();

  /*==================================================================================================
  Classes
  ==================================================================================================*/

  const classes = {
    Description: `mt-5 leading-relaxed font-semibold lg:text-lg md:text-[17px] sm:text-lg text-[17px] ${darkMode === false ? "text-blue-900/80" : "text-white/80"}`,
  };

  /*==================================================================================================
  Render
  ==================================================================================================*/

  return (
    <FadeUpMotion>
      <p className={classes.Description}>{t(Des.toLowerCase())}</p>
    </FadeUpMotion>
  );
}

/*====================================================================================================
End Component
======================================================================================================*/
