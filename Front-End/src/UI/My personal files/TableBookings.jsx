import { useMemo, useState } from "react";

//import RECENT_BOOKINGS, STATUS_CONFIG Data
import { RECENT_BOOKINGS, STATUS_CONFIG } from "../../Data/DashboardData";
import { INITIAL_LISTINGS } from "../../components/My personal files/My Listing/INITIAL_LISTINGS";

//import framer-motion
import { AnimatePresence, motion } from "framer-motion";

//import Components UI
import ToastCancelModal from "./Container Toast ALL Modals/ToastCancelModal";
import Container_Header from "./Container NEW IS Header With ALL Page/Container_Header";
import ContainerTable from "./Container Table/ContainerTable";

//
import ViewModalDetails from "./ViewModalDetails";
import CancelModalDetails from "./CancelModalDetails";
import BtnLoadMore from "./BtnLoadMore";
// import PaginationComponentUI from "../Tour_Hotel_Car_Food_Page/Section Right/Pagination";

/* ------------------------------------------------------------------ */
/* Sample Data                                                         */
/* ------------------------------------------------------------------ */

export default function TableBookings({ condition }) {
  //Step 1 => ALL orders
  const [orders, setOrders] = useState(RECENT_BOOKINGS);

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 2 => Count rows
  const [rows, setRows] = useState(5);

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 3 => visibleData
  const visibleData = orders.slice(0, rows);

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 4 => viewItem
  const [viewItem, setViewItem] = useState(null);

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 5 => cancelItem
  const [cancelItem, setCancelItem] = useState(null);

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 6 => loading
  const [loading, setLoading] = useState(false);

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 7 => toast
  const [toast, setToast] = useState(false);

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 8 => Function loadMore
  const loadMore = () => {
    setLoading(true);

    setTimeout(() => {
      setRows((prev) => prev + 3);
      setLoading(false);
    }, 700);
  };

  /////////////////////////////////////////////////////////////////////////////
  /////////////////////////////////////////////////////////////////////////////

  //Step 9 => Function confirmCancel
  const confirmCancel = () => {
    setOrders((prev) =>
      prev.map((item) =>
        item.id === cancelItem.id ? { ...item, status: "Cancelled" } : item,
      ),
    );

    setCancelItem(null);
    setToast(true);

    setTimeout(() => {
      setToast(false);
    }, 3200);
  };

  ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
  ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  // NEW Page IS My Listing ===>

  //listings
  const [listings, setListings] = useState(INITIAL_LISTINGS);

  //search
  const [search, setSearch] = useState("");

  //visibleCount
  const [visibleCount, setVisibleCount] = useState(rows);

  //loadingMore
  const [loadingMore, setLoadingMore] = useState(false);

  //modal
  const [modal, setModal] = useState({ type: null, listing: null });

  //filtered Search Title
  const filtered = useMemo(() => {
    const q = search.trim().toLowerCase();
    if (!q) return listings;
    return listings.filter((l) => l.title.toLowerCase().includes(q));
  }, [listings, search]);

  //visible
  const visible = filtered.slice(0, visibleCount);

  //remaining
  const remaining = filtered.length - visible.length;

  //Function handleLoadMore
  const handleLoadMore = () => {
    setLoadingMore(true);
    setTimeout(() => {
      setVisibleCount((v) => v + rows);
      setLoadingMore(false);
    }, 1000);
  };

  //Function closeModal
  const closeModal = () => setModal({ type: null, listing: null });

  //Function handleDeleteConfirm
  const handleDeleteConfirm = () => {
    setListings((prev) => prev.filter((l) => l.id !== modal.listing.id));
    closeModal();
  };

  //Function handleSaveEdit
  const handleSaveEdit = (updated) => {
    setListings((prev) => prev.map((l) => (l.id === updated.id ? updated : l)));
    closeModal();
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 120 }}
      animate={{ opacity: 50, y: 0 }}
      transition={{ delay: 0.5, duration: 1.5 }}
      style={{
        background: "#fff",
        borderRadius: 16,
        border: "1px solid #e2e8f0",
        overflow: "hidden",
      }}
    >
      {/* container Toast Modal */}
      <section>
        <ToastCancelModal toast={toast} />
      </section>
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* container NEW IS Header With ALL Page */}
      <container>
        <Container_Header
          condition={condition}
          orders={orders}
          //
          search={search}
          setSearch={setSearch}
          setVisibleCount={setVisibleCount}
          rows={rows}
        />
      </container>
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* container Table */}
      <container>
        <ContainerTable
          visibleData={visibleData}
          setViewItem={setViewItem}
          setCancelItem={setCancelItem}
          condition={condition}
        />
      </container>
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* Load More */}
      {rows < orders.length && (
        <BtnLoadMore loadMore={loadMore} loading={loading} />
      )}
      {/* OR */}
      {/* <PaginationComponentUI /> */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* View Modal */}
      <ViewModalDetails viewItem={viewItem} setViewItem={setViewItem} />,
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* Cancel Modal */}
      <CancelModalDetails
        cancelItem={cancelItem}
        setCancelItem={setCancelItem}
        confirmCancel={confirmCancel}
      />
    </motion.div>
  );
}
