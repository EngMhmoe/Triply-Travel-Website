//import React
import { useState } from "react";

export default function DataBox({ Data, booking, updateBooking }) {
  //convertDateTODay
  const [convertDateTODay, setConvertDateTODay] = useState();

  return (
    <section className="flex flex-col gap-2 font-semibold capitalize border border-(--primary-color) rounded-2xl p-4 cursor-pointer">
      <div className="flex items-center justify-between">
        <h1 className="text-lg">{Data.title}</h1>

        {/*  */}

        {Data.icon}
      </div>

      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}

      <div>
        <input
          type={Data.type}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}

          placeholder={
            Data.DefaultType === "Drop Off Location"
              ? "set Your Location"
              : Data.DefaultType === "Number of orders"
                ? "Number of orders"
                : ""
          }
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}

          value={
            Data.DefaultType === "Picking Up Location"
              ? booking.PickingUp
              : //////////////////////////////////////////////////////
                //////////////////////////////////////////////////////
                Data.DefaultType === "Pick Up Date"
                ? booking.PickUpDate
                : //////////////////////////////////////////////////////
                  //////////////////////////////////////////////////////
                  Data.DefaultType === "Pick Up Time"
                  ? booking.PickUpTime
                  : //////////////////////////////////////////////////////
                    //////////////////////////////////////////////////////
                    Data.DefaultType === "Drop Off Location"
                    ? booking.DropOff
                    : //////////////////////////////////////////////////////
                      //////////////////////////////////////////////////////
                      Data.DefaultType === "Drop Off Date"
                      ? booking.DropOffDate
                      : Data.DefaultType === "Drop Off Time"
                        ? //////////////////////////////////////////////////////
                          //////////////////////////////////////////////////////
                          booking.DropOffTime
                        : Data.DefaultType === "Number of orders"
                          ? //////////////////////////////////////////////////////
                            //////////////////////////////////////////////////////
                            booking.Quantity
                          : ""
          }
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
          // {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}

          onChange={(e) => {
            if (Data.DefaultType === "Picking Up Location") {
              updateBooking({
                PickingUp: e.target.value,
              });
            }

            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            else if (Data.DefaultType === "Pick Up Date") {
              updateBooking({
                PickUpDate: e.target.value,
              });

              const value = e.target.value; // "2026-06-26"

              const [year, month, day] = value.split("-");

              const date = new Date(year, month - 1, day);

              const dayName = date.toLocaleDateString("en-US", {
                weekday: "long",
              });

              setConvertDateTODay(dayName); // Friday
            }

            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            else if (Data.DefaultType === "Pick Up Time") {
              updateBooking({
                PickUpTime: e.target.value,
              });
            }

            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            else if (Data.DefaultType === "Drop Off Location") {
              updateBooking({
                DropOff: e.target.value,
              });
            }

            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            else if (Data.DefaultType === "Drop Off Date") {
              updateBooking({
                DropOffDate: e.target.value,
              });

              const value = e.target.value; // "2026-06-26"

              const [year, month, day] = value.split("-");

              const date = new Date(year, month - 1, day);

              const dayName = date.toLocaleDateString("en-US", {
                weekday: "long",
              });

              setConvertDateTODay(dayName); // Friday
            }

            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            else if (Data.DefaultType === "Drop Off Time") {
              updateBooking({
                DropOffTime: e.target.value,
              });
            }

            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            ////////////////////////////////////////////////////////////////////
            else if (Data.DefaultType === "Number of orders") {
              const value = e.target.value;
              if (value > 25 || value < 1) {
                return;
              }

              updateBooking({
                Quantity: value,
              });
            }
          }}
          className="text-xl text-(--primary-color) font-bold capitalize w-full border-0 outline-0"
        />
      </div>

      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}
      {/* ///////////////////////////////////////////////////////////////////////////////////////////////////// */}

      <div>
        <p>
          {Data.type === "text"
            ? "City, Airport Or Address"
            : Data.type === "date"
              ? convertDateTODay || "select date"
              : Data.type === "time"
                ? "Car Arrival Time"
                : Data.type === "number"
                  ? "Min: 1 , Max: 25"
                  : ""}
        </p>
      </div>
    </section>
  );
}
