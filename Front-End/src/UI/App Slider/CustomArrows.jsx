//============================================================
// Data
//============================================================
import { customArrow } from "../../Data/Home/customArrow";

//============================================================
// React Icons
//============================================================
import { GoChevronLeft, GoChevronRight } from "react-icons/go";

/*====================================================================================================
Step 2 ==> Component
======================================================================================================*/

export default function CustomArrows() {
  /*==================================================================================================
  Classes
  ==================================================================================================*/

  const classes = {
    Arrow:
      "absolute shadow-lg shadow-black top-[53%] translate-y-[-50%] z-10 w-11 h-11 bg--white text--(--primary-color) rounded-full shadow-lg flex items-center justify-center cursor-pointer bg-(--primary-pera) text-white transition duration-1000 text-2xl font-bold",
  };

  /*==================================================================================================
  Render
  ==================================================================================================*/

  return (
    <section>
      {customArrow.map((arrow) => (
        <div
          key={arrow.id}
          className={`custom-${arrow.customClass} ${classes.Arrow} ${arrow.position}`}
        >
          {arrow.customClass === "prev" ? (
            <GoChevronLeft />
          ) : (
            <GoChevronRight />
          )}
        </div>
      ))}
    </section>
  );
}

/*====================================================================================================
End Component
======================================================================================================*/
