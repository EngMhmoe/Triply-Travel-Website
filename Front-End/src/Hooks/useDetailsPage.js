import { useEffect, useState } from "react";

//import useNavigate
import { useNavigate, useParams } from "react-router-dom";

//import useToast
import { useToast } from "./useToast";

/*===========================================================
Start imports (1)
=============================================================*/


export function useDetailsPage({booking , requiredFields })
{
  //Step 1 ==> Styling TourDetailsPage
  const DetailsPage_Styling = {
    Styling1: "flex flex-col gap-50",

    ////////////////////////////////////////////////////////////////////////////////////
    ////////////////////////////////////////////////////////////////////////////////////

    Styling2: "lg:pt-105 md:pt-110 pt-125 mb-35",
  };

  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////

    const [getDataItemDetails, setDataItemDetails] = useState({});

  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////

  // const { documentId } = useParams();
  const { documentId } = useParams();

  //+++++++++++++++++++++++++++++++++++++++++++++++

  //Step 3 ==> setTourDataItemDetails
  useEffect(() => {
      const getLocalStorage = JSON.parse(localStorage.getItem("Details_Page"));
  
      setDataItemDetails(getLocalStorage);
  }, [documentId]);


  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////

  //Step 9 ==> isValid nights Tour
  const isValid = booking.nights > 0;

  /////////////////////////////////////////////////////////////////,
  /////////////////////////////////////////////////////////////////,

  //Step 10 ==> navigate
  const navigate = useNavigate();

  /////////////////////////////////////////////////////////////////,
  /////////////////////////////////////////////////////////////////,

  //Step 11 ==> toastError
  const { toastError } = useToast();

  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////
  ///////////////////////////////////////////////////////////////////////////////////////////////

  //Step 12 ==> handleBooking Tour
  const handleBooking = () => {
    //Step 1 , 2 ==> 
    if(requiredFields === "Tour" || requiredFields === "Destination" || requiredFields === "Hotel")
    {
      if (!booking.nights || booking.person <= 0) {
    
        return toastError("Please complete all fields");
      }
    }

    //Step 3 ==>
    if(requiredFields === "Car" )
    {
        if(!booking.PickUpDate || !booking.PickUpTime || !booking.DropOff || !booking.DropOffDate || !booking.DropOffTime)
        {
          return toastError("Please complete all fields");
        }
    }

    //Step 4 ==>
     if(requiredFields === "Food")
    {
        if(!booking.PickUpDate || !booking.PickUpTime || !booking.Quantity)
        {
          return toastError("Please complete all fields");
        }
    }


    
    const NEW = [getDataItemDetails];

    localStorage.setItem("CheckoutData" , JSON.stringify(NEW))

    localStorage.setItem("BookingSummaryCheckOut" , JSON.stringify(booking))

    localStorage.setItem("ISDetailsOrMore" ,"Details")
    
    navigate("/BookingCheckout_page");
  };

  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////////////



  return {
    DetailsPage_Styling,

    ///////////////////////////////////////////////
    ///////////////////////////////////////////////

    getDataItemDetails, 

    ///////////////////////////////////////////////
    ///////////////////////////////////////////////

    isValid,

    ///////////////////////////////////////////////
    ///////////////////////////////////////////////

    handleBooking,

    ///////////////////////////////////////////////
    ///////////////////////////////////////////////
  }
}
