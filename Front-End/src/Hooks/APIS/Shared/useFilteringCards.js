//import Stor usePagination
import { usePagination } from "../../../Store/APIS/usePaginationStor";


export function useFilteringCards_Shared(setFilterCards) {

    const { pagination , setPagination } = usePagination();





//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////





/*=================================================================
Step 1 ==> START ==>  Function filter { Category } ==> OK
===================================================================*/

    const FilterCategory = (categoryName) => {

        setPagination({
            ...pagination,
            page: 1,
        });

//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        /*====================================================

            const resultFilter = GetALLDataPage.filter(
                (item) => item.category === categoryName,
            );
            setALLFilteredData(resultFilter);
            
        =======================================================*/


// OR ==========================================================
// OR ==========================================================


        // NEW Filter Stripe ==> 
        /*===================================================================
        Array ده كده لو

        Example ==>
            const [category , setCategory] = [];
        =====================================================================
        setCategory(prev => {
            const result = [...prev , categoryName]
            return result;
        });    
        =======================================================================
        =======================================================================
        */

        //OR

        /*=====================================================================
        لو الفلتر عندك Checkbox، اعمل Toggle بدل ما تضيف القيمة كل مرة.
        عشان لو ضغط المستخدم على نفس الـ Category مرتين، تتشال بدل ما تتكرر.
        ========================================================================*/
        setFilterCards(prev => {

            //Step 1 ==>  Check is category IN Array ALL Categories ==> لو (false) معتعملش ده وكمل على ال بعده
            if (prev.categories.includes(categoryName)) {

                //Delete category Name IN ALLfilters.category == []
                const resultCategories = {
                    ...prev,

                    categories: prev.categories.filter(c => c !== categoryName),
                };
                return resultCategories;

            }
        

            ///////////////////////////////////////////////////////////////////////
            ///////////////////////////////////////////////////////////////////////


            //Step 2 ==> Add NEW category IN ALLfilters.category == []
            const resultCategories = {
                ...prev,

                categories: [...prev.categories, categoryName],
            }
            return resultCategories;

        });
    };

/*=================================================================
Step 1 ==> END ==>  Function filter { Category }
===================================================================*/





//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////





/*=================================================================
Step 2 ==> START ==>  Function filter { Range_Price } ==> OK
===================================================================*/

    const FilterPrice = (rangePriceValue) => {
    
        setPagination({
            ...pagination,
            page: 1,
        });


//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        setFilterCards(prev => ({
            ...prev,
            price: Number(rangePriceValue),
        }));
    
    };

/*=================================================================
Step 2 ==> END ==>  Function filter { Range_Price }
===================================================================*/





//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////





/*=================================================================
Step 3 ==> START ==>  Function filter { Language } ==> OK
===================================================================*/

    const FilterLanguage = (languageName) => {

        setPagination({
            ...pagination,
            page: 1,
        });


//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        /*========================================================

            const resultFilter = GetALLDataPage.filter(
                (item) => item.language === languageName,
            );

            setALLFilteredData(resultFilter);

        ==========================================================*/


// OR ==========================================================
// OR ==========================================================


        // NEW Filter Stripe ==> 
        setFilterCards(prev => {

            //Step 1 ==>  Check is language IN Array ALL languages
            if(prev.languages.includes(languageName))
            {
                //Delete language Name IN ALLfilters.language == []
                const resultLanguages = {
                    ...prev,

                    languages: prev.languages.filter(l => l !== languageName)
                }      
                return resultLanguages;

            }


            ///////////////////////////////////////////////////////////////////////
            ///////////////////////////////////////////////////////////////////////


            //Step 2 ==> Add NEW language IN ALLfilters.language == []
            const resultLanguages = {
                ...prev , 

                languages: [...prev.languages , languageName],
            };
            return resultLanguages;

        })
    };

/*=================================================================
Step 3 ==> END ==>  Function filter { Language }
===================================================================*/





//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////





/*=================================================================
Step 4 ==> START ==>  Function filter { ReviewScore } ==> OK
===================================================================*/

    const FilterReviewScore = (reviewScoreName) => {

        setPagination({
            ...pagination,
            page: 1,
        });


//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        /*========================================================

            const resultFilter = GetALLDataPage.filter(
                (item) => item.tag === reviewScore,
            );

            setALLFilteredData(resultFilter);

        ==========================================================*/


// OR ==========================================================
// OR ==========================================================


        // NEW Filter Stripe ==> 
        setFilterCards(prev => {

            //Step 1 ==>  Check is Tag IN Array ALL reviewScore
            if(prev.reviewScores.includes(reviewScoreName))
            {
                //Delete Tag Name IN ALLfilters.reviewScore == []
                const resultReviewScores = {
                    ...prev,

                    reviewScores: prev.reviewScores.filter(tag => tag !== reviewScoreName)
                }    
                return resultReviewScores;

            }


            ///////////////////////////////////////////////////////////////////////
            ///////////////////////////////////////////////////////////////////////


            //Step 2 ==> Add NEW Tag IN ALLfilters.reviewScore == []
            const resultReviewScores = {
                ...prev,

                reviewScores: [...prev.reviewScores, reviewScoreName] 
            };
            return resultReviewScores;

        })
    };

/*=================================================================
Step 4 ==> END ==>  Function filter { ReviewScore }
===================================================================*/





//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////





/*=================================================================
Step 5 ==> START ==>  Function filter { Search TopBar } ==> OK
===================================================================*/

    const FilterSearchTopBar = (searchName) => {
        
        setPagination({
            ...pagination,
            page: 1,
        });


//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        /*========================================================

            const resultFilter = GetALLDataPage.filter(
                (item) => item.title.toLowerCase().includes(searchName.toLowerCase()),
            );

            setALLFilteredData(resultFilter);

        ==========================================================*/


        /*========================================================
            const resultsSearch =
                search.length >= 2
                    ?GetALLDataPageSpider?.filter(
                        (blog) =>
                            blog.title.toLowerCase().includes(search.toLowerCase()) ||
                            blog.category.toLowerCase().includes(search.toLowerCase()) ||
                            blog.details.postBody.tags.some((tag) =>
                            tag.toLowerCase().includes(search.toLowerCase()),
                            ),)
                    :[];
        ==========================================================*/


// OR ==========================================================
// OR ==========================================================


        // NEW Filter Stripe ==> 
        setFilterCards(prev => {
            
            const resultSearchTitle = {
                ...prev,

                search: searchName.trim().toLowerCase()
            }
            return resultSearchTitle;

        })
    };

/*=================================================================
Step 5 ==> END ==>  Function filter { Search TopBar }
===================================================================*/

//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

/*=================================================================
Step 5 ==> START ==>  Function filter { Sort Bay TopBar } ==> OK
===================================================================*/

    const FilterSortBayTopBar = (sortName) => {         

        setPagination({
            ...pagination,
            page: 1,
        });


//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        setFilterCards(prev => ({
            ...prev,
            sort: sortName,
        }));

    };

/*=================================================================
Step 5 ==> END ==>  Function filter { Sort Bay TopBar }
===================================================================*/





    return {
        FilterCategory,
        //
        FilterPrice,
        //
        FilterLanguage,
        //
        FilterReviewScore,
        //
        FilterSearchTopBar,
        //
        FilterSortBayTopBar
    }
}
