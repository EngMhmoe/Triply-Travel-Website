import { useNavigate } from "react-router-dom";
import { usePagination } from "../../../../Store/APIS/usePaginationStor";


export default function useBlogFilterCards() {

    const { pagination , setPagination } = usePagination();

    const navigation = useNavigate();





//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////





/*=================================================================
Step 1 ==> START ==>  Function filter { NEW Blog } ==> NO
===================================================================*/

    const FilterTag = (tagName) => {

        setPagination({
            ...pagination,
            page: 1,
        });


//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        navigation(`/Blogs_page?tag=${tagName}`);

    }



///////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////



    const FilterCategory = (categoryName) => {

        setPagination({
            ...pagination,
            page: 1,
        });


//++++++++++++++++++++++++++++++++++++++++++
//++++++++++++++++++++++++++++++++++++++++++


        navigation(`/Blogs_page?category=${categoryName}`);

    }

/*=================================================================
Step 1 ==> END ==>  Function filter { NEW Blog }
===================================================================*/





    return {
        FilterTag,
        //
        FilterCategory
    }
}
