/*====================================================================================================
Step 2 ==> Start Custom Hook
======================================================================================================*/

export default function useHeaderScroll() {
  /*
  ====================================================================================================
  Step 2.1 ==> Start State
  ====================================================================================================
  */

  //============================================================
  // Controls Header Fixed State
  //============================================================

  const [isHeaderFixed, setIsHeaderFixed] = useState(false);

  /*
  ====================================================================================================
  Step 2.1 ==> End State
  ====================================================================================================
  */

  /*
  ====================================================================================================
  Step 2.2 ==> Start Effects
  ====================================================================================================
  */

  useEffect(() => {
    //==========================================================
    // Handle Scroll Event
    //==========================================================

    const handleScroll = () => {
      setIsHeaderFixed(
        window.scrollY >= HEADER_SCROLL_POSITION
      );
    };

    //==========================================================
    // Run Once After Component Mount
    //==========================================================

    handleScroll();

    //==========================================================
    // Add Scroll Listener
    //==========================================================

    window.addEventListener("scroll", handleScroll);

    //==========================================================
    // Cleanup Scroll Listener
    //==========================================================

    return () => {
      window.removeEventListener("scroll", handleScroll);
    };
  }, []);

  /*
  ====================================================================================================
  Step 2.2 ==> End Effects
  ====================================================================================================
  */

  /*
  ====================================================================================================
  Step 2.3 ==> Return Data
  ====================================================================================================
  */

  return isHeaderFixed;

  /*
  ====================================================================================================
  Step 2.3 ==> End Return Data
  ====================================================================================================
  */
}

/*====================================================================================================
Step 2 ==> End Custom Hook
======================================================================================================*/