//============================================================
// React
//============================================================
import { useEffect } from "react";

//============================================================
// Store
//============================================================
import { useDarkModeStore } from "../Store/useDarkModeStore";

/*====================================================================================================
End Imports
====================================================================================================*/

/*====================================================================================================
Start Hook
====================================================================================================*/

export default function useDark_AND_LightMode() {
  /*==================================================================================================
  Store
  ==================================================================================================*/

  const { DarkMode: darkMode, setDarkMode } = useDarkModeStore();

  /*==================================================================================================
  Functions
  ==================================================================================================*/

  const toggleDarkMode = () => {
    const newMode = !darkMode;

    setDarkMode(newMode);

    localStorage.setItem("selectedDarkMode", JSON.stringify(newMode));
  };

  /*==================================================================================================
  Effects
  ==================================================================================================*/

  useEffect(() => {
    const savedMode = localStorage.getItem("selectedDarkMode");

    if (savedMode !== null) {
      setDarkMode(JSON.parse(savedMode));
    }
  }, [setDarkMode]);

  /*==================================================================================================
  Return
  ==================================================================================================*/

  return {
    darkMode,
    toggleDarkMode,
  };
}

/*====================================================================================================
End Hook
====================================================================================================*/